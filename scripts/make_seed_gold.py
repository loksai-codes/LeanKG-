def build(prefix: str, lang: str, items: list[Item]) -> list[GoldExample]:
    out = []
    for i, (text, ents, rels) in enumerate(items, start=1):
        out.append(
            GoldExample(
                id=f"{prefix}-{lang}-{i:03d}",
                lang=lang,
                text=text,
                entities=[GoldEntity(text=s, type=t, id=cid) for s, t, cid in ents],
                relations=[
                    GoldRelation(head=h, tail=tl, type=r, negated=n) for h, r, tl, n in rels
                ],
                source="seed",
            )
        )
    return out


def main() -> None:
    root = Path(__file__).resolve().parents[1] / "domains"
    sets = {
        ("health_stress", "en"): ("hs", HS_EN),
        ("health_stress", "ja"): ("hs", HS_JA),
        ("manufacturing", "en"): ("mf", MF_EN),
        ("manufacturing", "ja"): ("mf", MF_JA),
    }
    for (pack, lang), (prefix, items) in sets.items():
        path = dump_gold(
            build(prefix, lang, items), root / pack / "eval" / "fixtures" / f"gold.{lang}.jsonl"
        )
        print(f"wrote {path} ({len(items)} sentences)")


if __name__ == "__main__":
    main()
